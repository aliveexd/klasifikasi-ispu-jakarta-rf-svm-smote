# ---------- 2. Uji McNemar eksak (binomial dua sisi) ----------
def mcnemar_exact(y, pred_a, pred_b):
    y, a, b = map(np.asarray, (y, pred_a, pred_b))
    n10 = int(np.sum((a == y) & (b != y)))   # A benar, B salah
    n01 = int(np.sum((a != y) & (b == y)))   # A salah, B benar
    p = 1.0 if n10 + n01 == 0 else binomtest(min(n10, n01), n10 + n01, 0.5).pvalue
    return n10, n01, p

# ---------- 3. Bootstrap berpasangan (selisih metrik A - B) ----------
def macro_f1(y, p):
    return f1_score(y, p, labels=np.unique(y), average="macro", zero_division=0)

def bootstrap_diff(y, pred_a, pred_b, metric=accuracy_score, B=10000, seed=42):
    y, a, b = map(np.asarray, (y, pred_a, pred_b))
    rng = np.random.default_rng(seed)
    n = len(y); d = np.empty(B)
    for i in range(B):
        idx = rng.integers(0, n, n)
        d[i] = metric(y[idx], a[idx]) - metric(y[idx], b[idx])
    lo, hi = np.percentile(d, [2.5, 97.5])
    return metric(y, a) - metric(y, b), lo, hi

